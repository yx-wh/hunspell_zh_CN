# 同一個 head 多行時加在 head 後的 flag。標準 hunspell 的 hashmgr 會把
# 「無 affix flag」的同形詞當重複詞去重，只留第一行（1.7.6 實測：发 st:發
# / 发 st:髮 只剩 發）；帶 flag 則走 next_homonym 分支，兩行都保留。
# 這個 flag 不必在 .aff 裡定義——未定義 flag 被忽略，不影響 spell()。
HOMONYM_FLAG = "X"


def validate_char_fix(fix):
    """白名單必須是單字對單字、無自映射、無鏈式摺疊。"""
    for src, dst in fix.items():
        if len(src) != 1 or len(dst) != 1:
            raise ValueError(f"CHAR_FIX 必須是單字對單字: {src!r} -> {dst!r}")
        if src == dst:
            raise ValueError(f"CHAR_FIX 自映射: {src!r}")
        if dst in fix:
            raise ValueError(f"CHAR_FIX 鏈式摺疊（單遍替換不會生效）: {src!r} -> {dst!r}")


def make_normalizer(cc):
    validate_char_fix(CHAR_FIX)

    def normalize(word: str) -> str:
        s = cc.convert(word).strip()
        if not s:
            return s
        return "".join(CHAR_FIX.get(ch, ch) for ch in s)
    return normalize


def main():
    if len(sys.argv) not in (3, 4):
        print("用法: python3 gen_zh_dic.py 詞彙表.txt 輸出.dic [異體字表.json]")
        sys.exit(1)

    in_path = sys.argv[1]
    out_path = sys.argv[2]
    # 可選：補進「完全沒有立目」的異體字，只寫正向 st:。
    variants_path = sys.argv[3] if len(sys.argv) == 4 else None

    # 繁體 -> 簡體，作為規範形式
    cc = OpenCC("t2s")
    cc_s2t = OpenCC("s2t")
    normalize = make_normalizer(cc)

    words = []
    seen = set()

    with open(in_path, "r", encoding="utf-8") as f:
        for line in f:
            w = line.strip()
            if not w or w.startswith("#"):
                continue
            if w not in seen:
                seen.add(w)
                words.append(w)

    # 統計每個字在「多字詞頭」裡的立目次數。words.txt 是 s2t 後的繁體詞頭，
    # 所以比對時也要看簡體形轉回繁體的結果，別把简体規範形誤判成冷僻字。
    freq = Counter()
    for w in words:
        if len(w) > 1:
            for ch in set(w):
                freq[ch] += 1

    def composes(ch):
        return freq[ch] >= 2 or freq[cc_s2t.convert(ch)] >= 2

    def attested(ch):
        return freq[ch] >= 1 or freq[cc_s2t.convert(ch)] >= 1

    def is_bmp(ch):
        return 0x4E00 <= ord(ch) <= 0x9FFF

    std_of = OrderedDict()        # 原詞 -> 規範形式
    variants = defaultdict(list)  # 規範形式 -> [原詞, ...]

    for w in words:
        #std = cc.convert(w).strip()
        std = normalize(w)
        if not std:
            continue
        std_of[w] = std
        if w not in variants[std]:
            variants[std].append(w)

    lines = []
    emitted_std = set()

    for w in words:
        std = std_of.get(w)
        if std is None or std in emitted_std:
            continue
        emitted_std.add(std)

        others = [v for v in variants[std] if v != std]
        if not others:
            # 繁簡相同、無變體，對 Goldendict 詞幹還原無用，跳過
            continue

        # 反向行（規範形 → 變體）只在該變體真的被辭典用來立目時保留。
        # 冷僻異體只需「異體 → 規範」這一側：電子書裡複製到的生僻字要能送到
        # 詞典條目；而「某字有哪些異體」是異體字字典的職責，交給 hunspell
        # 展開只會讓常用字每個位置都多幾個查空的候選。詞級變體一律保留。
        reverse = [v for v in others if len(v) != 1 or composes(v)]

        # 標準形→多個變體是「同一個 head、多行」，標準 hunspell 會去重，
        # 因此多於一個變體時給 head 加 flag（見 HOMONYM_FLAG 註釋）。
        homonym = f"/{HOMONYM_FLAG}" if len(reverse) > 1 else ""
        for v in others:
            lines.append(f"{v} st:{std}")
        for v in reverse:
            lines.append(f"{std}{homonym} st:{v}")

    if variants_path:
        with open(variants_path, "r", encoding="utf-8") as f:
            variant_groups = json.load(f)
        # 判据是「表裡有沒有這個字的正向行」，不是「在不在詞表」：只作為
        # 單字詞頭、但 normalize 原樣返回的字不會生成任何行，同樣要補。
        existing_heads = {
            line.split()[0].split("/", 1)[0]
            for line in lines if line.strip()
        }
        injected = 0
        for ch in sorted(set(variant_groups) - existing_heads):
            # 只補擴展區／兼容區的生僻異體。BMP 裡的「人/入」「大/太」
            # 是通假或形近組，拿來做映射只會污染常用字的查詢。
            if is_bmp(ch):
                continue
            group = variant_groups[ch]
            # 只認組內「真的被辭典用來立目」的 BMP 字當規範形
            anchor = next(
                (x for x in group
                 if len(x) == 1 and is_bmp(x) and attested(x)),
                None,
            )
            if anchor is None:
                continue
            target = normalize(anchor)
            if len(target) != 1 or target == ch:
                continue
            # 完全無立目：抹掉原形沒有損失，只寫正向，不寫反向
            lines.append(f"{ch} st:{target}")
            injected += 1
        print(f"從異體字表補進 {injected} 條正向行（無立目異體，只進不出）")

    # 并入「日本新字体→中文」(F1) 条目：去重、并跳过与简繁表重复的 jp==simp 字符。
    lines = merge_f1(lines)

    with open(out_path, "w", encoding="utf-8", newline="\n") as f:
        f.write(str(len(lines)) + "\n")
        if lines:
            f.write("\n".join(lines) + "\n")

    # 順便生成空殼 .aff；如果不想自動生成，可刪掉下面這段
    aff_path = os.path.splitext(out_path)[0] + ".aff"
    with open(aff_path, "w", encoding="utf-8", newline="\n") as f:
        f.write("SET UTF-8\n")
        f.write("LANG zh\n")
        f.write("FLAG long\n")

    # 写出 ja_JP.txt（中文→新字体，F2）；仅为完整 ja_JP.dic 的一部分，
    # 真正的日文 hunspell 还含日文词形还原（走らない→走る），需另行并入。
    # 真正的 .aff 由对方项目提供，此处不写。
    ja_dic = write_ja(os.path.dirname(out_path) or ".")
    if ja_dic:
        print(f"已生成: {ja_dic}")

    print(f"已生成: {out_path}")
    print(f"已生成: {aff_path}")


if __name__ == "__main__":
    main()

